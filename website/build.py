#!/usr/bin/env python3
"""Builds the MySSH website into website/dist (no dependencies).

    python3 website/build.py            # then: npx wrangler pages deploy website/dist --project-name myssh

One template (src/template.html), one strings file per language (src/i18n/*.json): English at /, 简体中文 at /zh/,
繁體中文 at /zh-tw/ (zh-tw.json: generated from zh.json with OpenCC s2twp, then reviewed), 日本語 at /ja/, 한국어 at /ko/. Screenshots come from docs/screenshots (regenerated by the ReadmeScreenshots test) plus website/static.
The version comes from Directory.Build.props; the download button points at the latest GitHub release.
"""
import hashlib
import html
import json
import os
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WEB = ROOT / "website"
SRC = WEB / "src"
DIST = WEB / "dist"
SITE = os.environ.get("MYSSH_SITE_URL", "https://myssh.pages.dev").rstrip("/")
LATEST = "https://github.com/dollarkillerx/MySSH/releases/latest/download/"
DOWNLOAD = LATEST + "MySSH-osx-Portable.zip"
DOWNLOAD_WIN = LATEST + "MySSH-win-Setup.exe"
DOWNLOAD_WIN_ZIP = LATEST + "MySSH-win-Portable.zip"
LANG_ORDER = ["en", "zh", "zh-tw", "ja", "ko"]
SCREENSHOTS = ["terminal-dark", "hosts-dark", "sftp-dark", "rdp-dark", "host-editor-light", "mcp-light"]


def version() -> str:
    props = (ROOT / "Directory.Build.props").read_text(encoding="utf-8")
    m = re.search(r"<Version>([^<]+)</Version>", props)
    return m.group(1).split("-")[0] if m else "0.0.0"


def main() -> None:
    ver = version()
    template = (SRC / "template.html").read_text(encoding="utf-8")
    css = (SRC / "style.css").read_text(encoding="utf-8")
    build = hashlib.sha256(css.encode()).hexdigest()[:10]
    langs = {k: json.loads((SRC / "i18n" / f"{k}.json").read_text(encoding="utf-8")) for k in LANG_ORDER}

    keys = set(re.findall(r"\{\{([a-zA-Z0-9_.]+)\}\}", template))
    for code, strings in langs.items():
        missing = sorted(k for k in keys if k not in GENERATED and k not in strings)
        if missing:
            raise SystemExit(f"{code}: missing strings {missing}")

    if DIST.exists():
        shutil.rmtree(DIST)
    (DIST / "assets").mkdir(parents=True)

    hreflang = "\n".join(
        [f'<link rel="alternate" hreflang="{s["_lang"]}" href="{SITE}{s["_path"]}">' for s in langs.values()]
        + [f'<link rel="alternate" hreflang="x-default" href="{SITE}/">'])

    for code, s in langs.items():
        current = ' aria-current="true"'
        menu = "".join(
            f'<li><a href="{o["_path"]}" hreflang="{o["_lang"]}" lang="{o["_lang"]}"{current if o is s else ""}'
            f' data-lang="{k}">{html.escape(o["_name"])}</a></li>'
            for k, o in langs.items())
        values = {
            "lang": s["_lang"], "langname": html.escape(s["_name"]), "langmenu": menu, "hreflang": hreflang,
            "home": s["_path"], "site": SITE, "canonical": SITE + s["_path"], "build": build,
            "download.url": DOWNLOAD, "download.win": DOWNLOAD_WIN, "download.winZip": DOWNLOAD_WIN_ZIP,
            "langredirect": REDIRECT if code == "en" else "",
        }
        for k, v in s.items():
            if not k.startswith("_"):
                values[k] = v.replace("{{version}}", ver)
        page = re.sub(r"\{\{([a-zA-Z0-9_.]+)\}\}", lambda m: values[m.group(1)], template)
        leftover = re.findall(r"\{\{[^}]*\}\}", page)
        if leftover:
            raise SystemExit(f"{code}: unreplaced {leftover}")
        out = DIST / s["_path"].strip("/") / "index.html" if s["_path"] != "/" else DIST / "index.html"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(page, encoding="utf-8")

    (DIST / "style.css").write_text(css, encoding="utf-8")
    for name in SCREENSHOTS:
        shutil.copy2(ROOT / "docs" / "screenshots" / f"{name}.png", DIST / "assets" / f"{name}.png")
    for f in (WEB / "static").iterdir():
        dest = DIST / "assets" / f.name if f.suffix == ".png" and f.name != "apple-touch-icon.png" else DIST / f.name
        shutil.copy2(f, dest)

    (DIST / "404.html").write_text(NOT_FOUND.replace("{{build}}", build), encoding="utf-8")
    (DIST / "robots.txt").write_text(f"User-agent: *\nAllow: /\nSitemap: {SITE}/sitemap.xml\n", encoding="utf-8")
    urls = "".join(f"<url><loc>{SITE}{s['_path']}</loc></url>" for s in langs.values())
    (DIST / "sitemap.xml").write_text(
        f'<?xml version="1.0" encoding="UTF-8"?><urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">{urls}</urlset>\n',
        encoding="utf-8")
    (DIST / "_headers").write_text(HEADERS, encoding="utf-8")
    print(f"built v{ver} → {DIST.relative_to(ROOT)} ({', '.join(s['_path'] for s in langs.values())})")


GENERATED = {"lang", "langname", "langmenu", "hreflang", "home", "site", "canonical", "build", "download.url", "download.win", "download.winZip", "langredirect"}

# Root page only: first visit follows the browser language; an explicit choice in the menu is remembered.
REDIRECT = """<script>
(function () {
  try {
    var pref = localStorage.getItem('myssh-lang');
    if (!pref) {
      var l = (navigator.languages && navigator.languages[0]) || navigator.language || '';
      pref = /^zh-(TW|HK|MO)|^zh-Hant/i.test(l) ? 'zh-tw' : /^zh/i.test(l) ? 'zh' : /^ja/i.test(l) ? 'ja' : /^ko/i.test(l) ? 'ko' : 'en';
    }
    if (['zh', 'zh-tw', 'ja', 'ko'].indexOf(pref) >= 0) location.replace('/' + pref + '/' + location.hash);
  } catch (e) {}
})();
</script>"""

NOT_FOUND = """<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Not found · MySSH</title><link rel="icon" href="/favicon.svg" type="image/svg+xml">
<link rel="stylesheet" href="/style.css?v={{build}}"></head>
<body><main class="section"><div class="wrap"><p class="eyebrow">404</p><h2>Page not found</h2>
<p class="lead" style="margin:16px 0 32px">This page does not exist. · 页面不存在。 · 頁面不存在。 · ページが見つかりません。 · 페이지를 찾을 수 없습니다.</p>
<a class="btn btn--primary" href="/"><span>MySSH</span></a></div></main></body></html>
"""

HEADERS = """/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  X-Frame-Options: DENY
  Permissions-Policy: camera=(), microphone=(), geolocation=()

/assets/*
  Cache-Control: public, max-age=86400

/style.css
  Cache-Control: public, max-age=31536000, immutable
"""

if __name__ == "__main__":
    main()
